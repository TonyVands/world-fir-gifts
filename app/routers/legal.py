from app.core import config

router = APIRouter(tags=["legal"])

PROJECT = "Всемирная ёлка подарков"


def _todo(text: str) -> str:
    return f'<mark class="todo">[{html.escape(text)}]</mark>'


def _op() -> dict[str, str]:
    esc = html.escape
    return {
        "name": esc(config.OPERATOR_NAME) if config.OPERATOR_NAME else _todo("ФИО или наименование оператора"),
        "status": esc(config.OPERATOR_STATUS) if config.OPERATOR_STATUS else _todo("статус: физическое лицо / самозанятый / ИП"),
        "inn": f"ИНН {esc(config.OPERATOR_INN)}" if config.OPERATOR_INN else _todo("ИНН (если есть)"),
        "email": (
            f'<a href="mailto:{esc(config.OPERATOR_EMAIL)}">{esc(config.OPERATOR_EMAIL)}</a>'
            if config.OPERATOR_EMAIL
            else _todo("e-mail для обращений")
        ),
        "address": esc(config.OPERATOR_ADDRESS) if config.OPERATOR_ADDRESS else _todo("адрес для писем"),
        "location": (
            esc(config.DATA_LOCATION)
            if config.DATA_LOCATION
            else _todo("страна размещения базы данных — должна быть Российская Федерация")
        ),
    }


def _site(request: Request) -> str:
    base = config.PUBLIC_URL or str(request.base_url).rstrip("/")
    return html.escape(base)


def _version_text() -> str:
    try:
        d = date.fromisoformat(config.LEGAL_VERSION)
        months = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"]
        return f"{d.day} {months[d.month - 1]} {d.year} г."
    except ValueError:
        return html.escape(config.LEGAL_VERSION)


def _purge_text() -> str:
    try:
        d = date.fromisoformat(config.PURGE_CONTACTS_AFTER)
        return d.strftime("%d.%m.%Y")
    except ValueError:
        return html.escape(config.PURGE_CONTACTS_AFTER)


